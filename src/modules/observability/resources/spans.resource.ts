    p95: 'ROUND(COALESCE(percentile_cont(0.95) WITHIN GROUP (ORDER BY duration_ms), 0))::int',
    p99: 'ROUND(COALESCE(percentile_cont(0.99) WITHIN GROUP (ORDER BY duration_ms), 0))::int',
